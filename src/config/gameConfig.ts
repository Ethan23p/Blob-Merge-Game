const STORAGE_KEY = 'gravity_blobs_custom_config_v6';

export function loadSavedConfig(): ConfigMap {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_CONFIG;
    const parsed = JSON.parse(raw);
    const result: ConfigMap = { ...DEFAULT_CONFIG };
    for (const key of Object.keys(DEFAULT_CONFIG)) {
      if (parsed[key]) {
        result[key] = {
          ...DEFAULT_CONFIG[key],
          value: parsed[key].value ?? DEFAULT_CONFIG[key].value,
          enabledInTopBar: parsed[key].enabledInTopBar ?? DEFAULT_CONFIG[key].enabledInTopBar,
        };
      }
    }
    return result;
  } catch {
    return DEFAULT_CONFIG;
  }
}

export function saveConfigToStorage(config: ConfigMap) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
  } catch (e) {
    console.error('Failed to save config:', e);
  }
}
